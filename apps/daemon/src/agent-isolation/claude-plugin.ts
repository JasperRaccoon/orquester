/**
 * Agent isolation — the Orquester-generated local Claude Code plugin that
 * carries a profile's skills and commands (spec §6.1).
 *
 * A profile chat runs with `settingSources: ["project", "local"]`, so the
 * user's `~/.claude/skills` and `commands` are not loaded; the profile's own
 * come in through the SDK `plugins` option as one local plugin:
 *
 *   <dir>/.claude-plugin/plugin.json   { "name": <name>, … }
 *   <dir>/skills/<skill>/SKILL.md      (+ the skill's other files)
 *   <dir>/commands/<cmd>.md            (`git/pr` → commands/git/pr.md)
 *
 * Claude Code 2.1.285 names a plugin skill `<plugin>:<skill directory>` and a
 * plugin command `<plugin>:<sub>:<file stem>` (subdirectories joined by `:`),
 * read from the binary. The SDK `skills` allow-list matches an entry against a
 * name exactly or as a `:<entry>` suffix; the launcher passes the qualified
 * ids returned here, which matter for commands: without them they vanish from
 * the model's listing.
 */

import { randomBytes } from "node:crypto";
import { lstat, mkdir, rename, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { isValidCommandName, isValidSkillName } from "@orquester/api";
import { claudePluginSkillName } from "./claude-names.ts";
import { copyTree } from "../agent-profile/infra/tree.ts";

/** Claude's plugin-name rule (no `@`, `:`, whitespace or separators), kept to a plain slug. */
const PLUGIN_NAME = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;

export interface ClaudeLocalPluginInput {
  /** Where the plugin is written; replaced as a whole. Its parent is created. */
  dir: string;
  /** The plugin name (and so the id prefix). */
  name: string;
  description?: string;
  /** Each `sourceDir` holds a `SKILL.md`; it may itself be a symlink (followed). Symlinks inside are skipped. */
  skills: readonly { name: string; sourceDir: string }[];
  /** `name` may carry one folder level (`git/pr`); `markdown` is the whole file, frontmatter included. */
  commands: readonly { name: string; markdown: string }[];
}

export interface ClaudeLocalPlugin {
  /** The plugin directory, for the SDK `plugins: [{ type: "local", path }]`. */
  path: string;
  name: string;
  /** `<plugin>:<skill>`, in input order. */
  skillIds: string[];
  /** `<plugin>:<cmd>` (`git/pr` → `<plugin>:git:pr`), in input order. */
  commandIds: string[];
  /** `skillIds` then `commandIds`: what the launcher puts in the SDK `skills` list. */
  allowlist: string[];
}

/**
 * Writes the plugin (see the module header) into a staging directory beside
 * `dir`, then swaps it into place, so a launch never sees a half-written
 * plugin. Throws on an invalid plugin, skill or command name, two items with
 * the same id, or a skill source without `SKILL.md`; nothing is replaced then.
 */
export async function generateClaudeLocalPlugin(input: ClaudeLocalPluginInput): Promise<ClaudeLocalPlugin> {
  if (!PLUGIN_NAME.test(input.name)) {
    throw new Error(`"${input.name}" is not a valid Claude plugin name.`);
  }
  const ids = new Set<string>();
  const claim = (id: string): string => {
    if (ids.has(id)) throw new Error(`Two items of the plugin would both be named "${id}".`);
    ids.add(id);
    return id;
  };
  const skillIds = input.skills.map((skill) => {
    if (!isValidSkillName(skill.name)) throw new Error(`"${skill.name}" is not a valid skill name.`);
    return claim(claudePluginSkillName(input.name, skill.name));
  });
  const commandIds = input.commands.map((command) => {
    if (!isValidCommandName(command.name)) throw new Error(`"${command.name}" is not a valid command name.`);
    return claim(`${input.name}:${command.name.split("/").join(":")}`);
  });
  for (const skill of input.skills) {
    const skillFile = join(skill.sourceDir, "SKILL.md");
    if (!(await stat(skillFile).then((st) => st.isFile()).catch(() => false))) {
      throw new Error(`The skill "${skill.name}" has no SKILL.md in ${skill.sourceDir}.`);
    }
  }

  const tag = randomBytes(6).toString("hex");
  const staging = `${input.dir}.staging-${tag}`;
  await mkdir(dirname(input.dir), { recursive: true });
  try {
    await mkdir(join(staging, ".claude-plugin"), { recursive: true, mode: 0o700 });
    const manifest = {
      name: input.name,
      version: "1.0.0",
      description: input.description ?? "Generated by Orquester for an Agent Profile.",
      author: { name: "Orquester" }
    };
    await writeFile(join(staging, ".claude-plugin", "plugin.json"), `${JSON.stringify(manifest, null, 2)}\n`);
    if (input.skills.length > 0) {
      await mkdir(join(staging, "skills"));
      for (const skill of input.skills) {
        await copyTree(skill.sourceDir, join(staging, "skills", skill.name), { refuseSymlinks: false });
      }
    }
    if (input.commands.length > 0) {
      for (const command of input.commands) {
        const file = join(staging, "commands", `${command.name}.md`);
        await mkdir(dirname(file), { recursive: true });
        await writeFile(file, command.markdown);
      }
    }
    await swapIntoPlace(staging, input.dir, tag);
  } catch (error) {
    await rm(staging, { recursive: true, force: true });
    throw error;
  }
  return { path: input.dir, name: input.name, skillIds, commandIds, allowlist: [...skillIds, ...commandIds] };
}

/** Moves the old `dir` aside, `staging` in, then drops the old one. */
async function swapIntoPlace(staging: string, dir: string, tag: string): Promise<void> {
  const present = await lstat(dir).then(
    () => true,
    () => false
  );
  if (!present) {
    await rename(staging, dir);
    return;
  }
  const old = `${dir}.old-${tag}`;
  await rename(dir, old);
  try {
    await rename(staging, dir);
  } catch (error) {
    await rename(old, dir).catch(() => undefined);
    throw error;
  }
  await rm(old, { recursive: true, force: true });
}
