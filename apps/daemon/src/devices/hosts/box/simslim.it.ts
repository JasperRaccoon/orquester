/**
 * Generates the box-side script of the simslim integration run on a rented Mac (not part of
 * `pnpm test`; see `../../README.md`). The script is made from the same constants and command
 * builders the box host runs — the pinned tools and simslim install, the slim profile, `simslim
 * on/verify/top/measure`, the boot-frame check — and measures, on one Mac:
 *
 * - a stock simulator's memory (`simslim measure`) and cold boot to a rendered frame;
 * - two pool simulators made like the host makes them (one also primed with agent-device), each
 *   leased (renamed, booted) — boot to frame and `simslim verify`;
 * - a lease's slim first boot with an empty pool (`simslim on` boots it);
 * - every slim simulator's memory, `simslim top`, the Mac's memory pressure;
 * - agent-device `open` + `snapshot -i` on an unprimed and a primed slim simulator;
 * - the hub's MJPEG stream of a slim simulator;
 * - density: slim simulators booted up to 8 at once, the Mac's used memory and load each step.
 *
 *   cd apps/daemon && TSX_DISABLE_CACHE=1 node --import tsx src/devices/hosts/box/simslim.it.ts <out dir>
 *
 * writes `<out dir>/run.sh`; a temporary workflow runs `bash run.sh <results dir>` on the runner.
 */

import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { BOX_DEVICES_DIR, SIMSLIM_INSTALL_SCRIPT } from "../../../boxes/github/device-cache.ts";
import { DEVICE_TOOL_PACKAGES, IOS_VM_STREAM_FLAGS, remoteLayout } from "./remote.ts";
import { FRAME_SIZE_SCRIPT, POOL_PREP_SIM_PREFIX, REAL_FRAME_MIN_PNG_BYTES, leaseSimulatorName } from "./simctl.ts";
import { poolSimulatorName } from "./sim-pool.ts";
import { ORQ_SLIM_PROFILE_JSON, SIMSLIM_ENV, simslimBin, simslimMeasureArgs, simslimOnArgs, simslimProfilePath, simslimTopArgs, simslimVerifyArgs } from "./simslim.ts";

const out = process.argv[2];
if (!out) {
  console.error("usage: simslim.it.ts <out dir>");
  process.exit(2);
}

/** Shell words: `$VAR` stays a quoted expansion, everything else is single-quoted. */
function words(args: readonly string[]): string {
  return args.map((arg) => (/^\$[A-Z_][A-Z0-9_]*$/.test(arg) ? `"${arg}"` : `'${arg.replace(/'/g, `'\\''`)}'`)).join(" ");
}

const layout = remoteLayout({ provider: "blacksmith", home: "/Users/runner" });
const PROFILE_ID = "iphone-17-pro";
const on = (udid: string, extra: { preserveBootState?: boolean } = {}) => words(simslimOnArgs({ udid, profilePath: "$PROFILE", ...extra }));
const verify = (udid: string) => words(simslimVerifyArgs({ udid, profilePath: "$PROFILE" }));

const script = `#!/bin/bash
# Generated by apps/daemon/src/devices/hosts/box/simslim.it.ts — do not edit.
set -uo pipefail
OUT=$1
mkdir -p "$OUT"
exec > >(tee -a "$OUT/run.log") 2>&1
export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH" FORCE_COLOR=0 NO_COLOR=1 AGENT_DEVICE_NO_UPDATE_NOTIFIER=1
${Object.entries(SIMSLIM_ENV)
  .map(([key, value]) => `export ${key}=${value}`)
  .join("\n")}
ROOT=${BOX_DEVICES_DIR}
TOOLS=${layout.tools}
SIMSLIM=${simslimBin(layout.tools)}
PROFILE=${simslimProfilePath(layout.root)}
AD=${layout.agentDeviceEntry}
HUB=${layout.hubEntry}
mkdir -p "$ROOT" "$TOOLS"
now() { perl -MTime::HiRes=time -e 'printf "%.2f", time'; }
since() { perl -e 'printf "%.2f", $ARGV[1]-$ARGV[0]' "$1" "$(now)"; }
timing() { echo "$1=$2" | tee -a "$OUT/timings.txt"; }
note() { echo; echo "=== $* ($(date -u +%H:%M:%S))"; }
# The Mac's used memory (top's PhysMem line), swap and load, under a label.
host_mem() { echo "$1 $(top -l 1 -n 0 | grep PhysMem) | $(sysctl -n vm.swapusage) | load $(sysctl -n vm.loadavg)" | tee -a "$OUT/host-mem.txt"; }
frame_size() { /bin/sh -c ${words([FRAME_SIZE_SCRIPT])} frame "$1" "$OUT/frame-$1.png"; }
# Until a screenshot is a rendered screen (the host's REAL_FRAME_MIN_PNG_BYTES), at most 90 s.
wait_frame() {
  local end=$(( $(date +%s) + 90 )) bytes=0
  while [ "$(date +%s)" -lt "$end" ]; do
    bytes=$(frame_size "$1")
    [ "\${bytes:-0}" -ge ${REAL_FRAME_MIN_PNG_BYTES} ] && return 0
    sleep 1
  done
  echo "no rendered frame for $1 (last $bytes bytes)"
  return 1
}
simslim() { "$SIMSLIM" "$@"; }
ad() { node "$AD" "$@"; }

note environment
sw_vers; sysctl hw.memsize hw.ncpu kern.hv_vmm_present; xcodebuild -version; node --version; uptime
xcrun simctl list runtimes | grep -i ios
echo "memsize_bytes=$(sysctl -n hw.memsize)" >> "$OUT/timings.txt"
host_mem baseline

note "device tools (pinned)"
t=$(now)
( cd "$TOOLS" && { [ -f package.json ] || printf '{ "private": true }\\n' > package.json; } && npm install --no-audit --no-fund --save-exact ${words(DEVICE_TOOL_PACKAGES)} > "$OUT/npm.log" 2>&1 ) || { tail -20 "$OUT/npm.log"; exit 1; }
timing tools_install_s "$(since "$t")"

note "simslim install (the host's script)"
t=$(now)
TOOLS="$TOOLS" /bin/sh -c ${words([SIMSLIM_INSTALL_SCRIPT])} simslim-install | tee "$OUT/simslim-install.txt" || exit 1
timing simslim_install_s "$(since "$t")"
t=$(now)
TOOLS="$TOOLS" /bin/sh -c ${words([SIMSLIM_INSTALL_SCRIPT])} simslim-install > /dev/null
timing simslim_install_again_s "$(since "$t")"
cat > "$PROFILE" << 'PROFILE_JSON'
${ORQ_SLIM_PROFILE_JSON.trimEnd()}
PROFILE_JSON
simslim profiles > "$OUT/simslim-profiles.txt" 2>&1 || true

note "target"
picked=$(xcrun simctl list -j devicetypes runtimes | node -e '
const data = JSON.parse(require("fs").readFileSync(0, "utf8"));
const v = (r) => String(r.version || "0").split(".").map(Number);
const cmp = (a, b) => { const x = v(a), y = v(b); for (let i = 0; i < Math.max(x.length, y.length); i++) if ((x[i] || 0) !== (y[i] || 0)) return (x[i] || 0) - (y[i] || 0); return 0; };
const rt = (data.runtimes || []).filter((r) => r.isAvailable && (r.platform === "iOS" || String(r.identifier).includes(".iOS-"))).sort(cmp).pop();
const types = rt ? rt.supportedDeviceTypes || [] : [];
const type = types.find((t) => t.name === "iPhone 17 Pro") || types.filter((t) => t.productFamily === "iPhone").pop();
if (!rt || !type) process.exit(1);
console.log(rt.identifier + " " + type.identifier + " " + rt.version);
') || { echo "no iOS runtime"; exit 1; }
RUNTIME=\${picked%% *}; rest=\${picked#* }; TYPE=\${rest%% *}; IOS=\${rest#* }
echo "runtime=$RUNTIME type=$TYPE ios=$IOS" | tee -a "$OUT/timings.txt"

note "stock baseline: cold boot, settle, measure"
S=$(xcrun simctl create orq-it-stock "$TYPE" "$RUNTIME")
t=$(now); xcrun simctl boot "$S"; xcrun simctl bootstatus "$S" -b > /dev/null; timing stock_bootstatus_s "$(since "$t")"
wait_frame "$S"; timing stock_boot_to_frame_s "$(since "$t")"
sleep 45
host_mem stock-1
simslim ${words(simslimMeasureArgs("$S"))} | tee "$OUT/measure-stock.json"; echo
simslim ${words(simslimTopArgs())} > "$OUT/top-stock.json"
memory_pressure -Q | tee "$OUT/pressure-stock.txt"

note "agent-device runner build + first session (stock simulator)"
t=$(now); ad open com.apple.Preferences --platform ios --udid "$S" --session it-stock > "$OUT/ad-stock-open.txt" 2>&1; echo "rc=$?"; timing ad_stock_first_open_s "$(since "$t")"
t=$(now); ad snapshot -i --session it-stock > "$OUT/ad-stock-snapshot.txt" 2>&1; echo "rc=$?"; timing ad_stock_snapshot_s "$(since "$t")"
ad close --session it-stock > /dev/null 2>&1 || true
t=$(now); xcrun simctl shutdown "$S"; timing stock_shutdown_s "$(since "$t")"
xcrun simctl delete "$S"

# A pool simulator as the host makes it: orq-poolprep-*, simslim on (one boot, back to shut down), renamed.
make_pool() {
  local id=$1 prime=$2 udid
  udid=$(xcrun simctl create "${POOL_PREP_SIM_PREFIX}$id" "$TYPE" "$RUNTIME")
  local t=$(now)
  if [ "$prime" = 1 ]; then
    U=$udid; simslim ${on("$U")} > "$OUT/pool-$id-on.txt" 2>&1 || { cat "$OUT/pool-$id-on.txt"; return 1; }
    timing pool_\${id}_slim_boot_s "$(since "$t")"
    local p=$(now)
    ad open com.apple.Preferences --platform ios --udid "$udid" --session prime-$id > "$OUT/pool-$id-prime.txt" 2>&1
    ad snapshot -i --session prime-$id >> "$OUT/pool-$id-prime.txt" 2>&1
    ad close --session prime-$id >> "$OUT/pool-$id-prime.txt" 2>&1
    timing pool_\${id}_prime_s "$(since "$p")"
    xcrun simctl shutdown "$udid"
  else
    U=$udid; simslim ${on("$U", { preserveBootState: true })} > "$OUT/pool-$id-on.txt" 2>&1 || { cat "$OUT/pool-$id-on.txt"; return 1; }
  fi
  timing pool_\${id}_make_s "$(since "$t")"
  xcrun simctl rename "$udid" "${poolSimulatorName(PROFILE_ID, "$id")}"
  echo "$udid"
}
note "pool: two simulators, one at a time (the second primed with agent-device)"
P1=$(make_pool p1 0 | tail -1); P2=$(make_pool p2 1 | tail -1)
echo "P1=$P1 P2=$P2"
xcrun simctl list devices | grep orq- || true
ls -la /private/var/tmp/com.apple.CoreSimulator.SimDevice.$P1/ 2>/dev/null | head

# A lease from the pool: renamed orq-<leaseId>, booted, then verified.
lease_boot() {
  local udid=$1 name=$2 key=$3
  xcrun simctl rename "$udid" "$name"
  local t=$(now)
  xcrun simctl boot "$udid"; xcrun simctl bootstatus "$udid" -b > /dev/null; timing \${key}_bootstatus_s "$(since "$t")"
  wait_frame "$udid"; timing \${key}_boot_to_frame_s "$(since "$t")"
  t=$(now); U=$udid; simslim ${verify("$U")} > "$OUT/verify-$key.json"; echo "verify rc=$?"; timing \${key}_verify_s "$(since "$t")"
  cat "$OUT/verify-$key.json"; echo
}
note "lease L1 from the pool (unprimed)"
lease_boot "$P1" ${leaseSimulatorName("it-L1")} pool1
note "lease L2 from the pool (primed)"
lease_boot "$P2" ${leaseSimulatorName("it-L2")} pool2

note "lease L3 with an empty pool: slim first boot"
L3=$(xcrun simctl create ${leaseSimulatorName("it-L3")} "$TYPE" "$RUNTIME")
t=$(now); U=$L3; simslim ${on("$U")} > "$OUT/l3-on.txt" 2>&1; echo "rc=$?"; timing fresh_slim_on_s "$(since "$t")"
xcrun simctl bootstatus "$L3" -b > /dev/null; wait_frame "$L3"; timing fresh_slim_boot_to_frame_s "$(since "$t")"
U=$L3; simslim ${verify("$U")} > "$OUT/verify-fresh.json"; cat "$OUT/verify-fresh.json"; echo

note "three slim simulators booted: settle, measure"
sleep 45
for U in "$P1" "$P2" "$L3"; do simslim ${words(simslimMeasureArgs("$U"))} | tee "$OUT/measure-slim-$U.json"; echo; done
t=$(now); simslim ${words(simslimTopArgs())} > "$OUT/top-slim.json"; timing top_s "$(since "$t")"
cat "$OUT/top-slim.json"; echo
memory_pressure -Q | tee "$OUT/pressure-slim.txt"
host_mem slim-3
vm_stat > "$OUT/vm_stat-slim.txt"

note "agent-device on slim simulators: L1 unprimed, L2 primed"
for pair in "l1:$P1" "l2:$P2"; do
  k=\${pair%%:*}; U=\${pair#*:}
  t=$(now); ad open com.apple.Preferences --platform ios --udid "$U" --session it-$k > "$OUT/ad-$k-open.txt" 2>&1; echo "rc=$?"; timing ad_\${k}_open_s "$(since "$t")"
  t=$(now); ad snapshot -i --session it-$k > "$OUT/ad-$k-snapshot.txt" 2>&1; echo "rc=$?"; timing ad_\${k}_snapshot_s "$(since "$t")"
  t=$(now); ad snapshot -i --session it-$k > /dev/null 2>&1; timing ad_\${k}_snapshot2_s "$(since "$t")"
  grep -c '@e' "$OUT/ad-$k-snapshot.txt" | sed "s/^/ad_\${k}_refs=/" | tee -a "$OUT/timings.txt"
  grep -m3 -E 'General|Settings' "$OUT/ad-$k-snapshot.txt" || echo "no Settings rows in the $k snapshot"
done
for k in l1 l2; do ad close --session it-$k > /dev/null 2>&1 || true; done

note "hub MJPEG of slim L3"
H=$OUT/hub-state; mkdir -p "$H"
EXPO_DEVICE_HUB_STATE_DIR="$H" node "$HUB" --port 7341 --host 127.0.0.1 --hide-sidebar --hide-boot-device --platform ios ${words(IOS_VM_STREAM_FLAGS)} > /dev/null 2> "$OUT/hub.stderr.log" &
HUBPID=$!
for i in $(seq 1 120); do curl -sf -o /dev/null http://127.0.0.1:7341/readyz && break; sleep 0.5; done
B=http://127.0.0.1:7341/vendor/serve-sim
t=$(now); curl -s -X POST "$B/grid/api/start" -H 'content-type: application/json' -d "{\\"udid\\":\\"$L3\\"}" -w ' start http=%{http_code}\\n'; timing hub_start_s "$(since "$t")"
curl -sN --max-time 6 "$B/helper/$L3/stream.mjpeg" -o "$OUT/l3.mjpeg"
parts=$(grep -ac -- '--frame' "$OUT/l3.mjpeg"); bytes=$(wc -c < "$OUT/l3.mjpeg" | tr -d ' ')
timing hub_mjpeg_parts_6s "$parts"; timing hub_mjpeg_bytes_6s "$bytes"
curl -s -X POST "$B/grid/api/shutdown" -H 'content-type: application/json' -d "{\\"udid\\":\\"$L3\\"}" -w ' shutdown http=%{http_code}\\n'
kill "$HUBPID" 2> /dev/null; wait "$HUBPID" 2> /dev/null
rm -f "$OUT/l3.mjpeg" "$OUT"/frame-*.png

note "density: slim simulators up to 8 booted, one boot at a time"
for n in 4 5 6 7 8; do
  U=$(xcrun simctl create ${leaseSimulatorName("it-D")}$n "$TYPE" "$RUNTIME")
  t=$(now); simslim ${on("$U")} > /dev/null 2>&1; xcrun simctl bootstatus "$U" -b > /dev/null; wait_frame "$U"; timing density_\${n}_boot_to_frame_s "$(since "$t")"
  host_mem "slim-$n-fresh"
done
sleep 60
host_mem slim-8-settled
simslim ${words(simslimTopArgs())} > "$OUT/top-slim-8.json"
memory_pressure -Q | tee "$OUT/pressure-slim-8.txt"
rm -f "$OUT"/frame-*.png

note cleanup
for U in $(xcrun simctl list -j devices | node -e 'const d = JSON.parse(require("fs").readFileSync(0, "utf8")).devices; for (const l of Object.values(d)) for (const s of l) if (s.name.startsWith("orq-")) console.log(s.udid)'); do
  xcrun simctl shutdown "$U" > /dev/null 2>&1; xcrun simctl delete "$U"
done
note done
cat "$OUT/timings.txt"
`;

await mkdir(out, { recursive: true });
await writeFile(join(out, "run.sh"), script, { mode: 0o755 });
console.log(join(out, "run.sh"));
